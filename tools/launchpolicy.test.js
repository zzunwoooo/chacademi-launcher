const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const zlib = require('zlib')
const policy = require('../app/assets/js/serverpolicy')
const session = require('../app/assets/js/gamesession')
const {EventEmitter} = require('events')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'chacademi-launch-policy-'))
const server = {id:'launcher_v2-1.21.4', address:'스트리머.온라인.한국'}
const target = path.join(root, 'servers.dat')
try {
    assert.equal(policy.prepare(root, {...server, id:'other'}), false)
    assert.equal(fs.existsSync(target), false)
    assert.equal(policy.prepare(root, server), true)
    const initial = fs.readFileSync(target)
    assert(initial.includes(Buffer.from('acceptTextures')))
    assert(initial.includes(Buffer.from('스트리머.온라인.한국')))
    policy.prepare(root, server)
    assert.deepEqual(fs.readFileSync(target), initial, 'repeat does not duplicate entries')
    assert.deepEqual(fs.readFileSync(target + '.chacademi-backup'), initial)
    const other = Buffer.from(initial)
    // Replace same-byte-length UTF-8 server address with a different server; preserve its deny flag.
    const at = other.indexOf(Buffer.from(server.address))
    Buffer.alloc(Buffer.byteLength(server.address), 97).copy(other, at)
    const allow = other.indexOf(Buffer.from('acceptTextures')) + Buffer.byteLength('acceptTextures')
    other[allow] = 0
    fs.writeFileSync(target, other)
    policy.prepare(root, server)
    const combined = fs.readFileSync(target)
    assert(combined.includes(other.subarray(18, other.length - 1)), 'unrelated entry remains byte-identical')
    assert.equal(combined[allow], 0)
    fs.writeFileSync(target, zlib.gzipSync(initial))
    policy.prepare(root, server)
    assert.deepEqual(zlib.gunzipSync(fs.readFileSync(target)), initial)
    fs.writeFileSync(target, Buffer.from([10,0]))
    assert.throws(() => policy.prepare(root, server), /Invalid/)
    assert.deepEqual(fs.readFileSync(target), Buffer.from([10,0]), 'corruption is not overwritten')
    const child = new EventEmitter(); child.pid = process.pid
    session.check(root)
    session.track(root, child); child.emit('spawn')
    assert.throws(() => session.check(root), /실행 중/)
    child.emit('close')
    session.check(root)
    console.log('PASS server scoping, fresh/repeat, backup, unrelated deny preservation, gzip, corruption, live game lock and cleanup')
} finally { fs.rmSync(root, {recursive:true, force:true}) }
