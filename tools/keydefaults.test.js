const assert = require('assert/strict')
const fs = require('fs')
const path = require('path')
const os = require('os')
const policy = require('../app/assets/js/keydefaults')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'chacademi-key-defaults-'))
const target = path.join(root, 'options.txt')
try {
    const state = policy.capture(root)
    fs.writeFileSync(target, 'music:0.4\nkey_key.plasmovoice.settings:key.keyboard.v\nkey_key.magiccodex.open:key.keyboard.i\nkey_key.wi_zoom.zoom:key.keyboard.z\n')
    policy.apply(root, state)
    let content = fs.readFileSync(target, 'utf8')
    assert(content.includes('key_key.plasmovoice.settings:key.keyboard.n'))
    assert(content.includes('key_key.magiccodex.open:key.keyboard.k'))
    assert(content.includes('music:0.4'))
    assert(content.includes('key_key.wi_zoom.zoom:key.keyboard.z'), 'unpictured keys unchanged')
    fs.writeFileSync(target, 'music:0.8\r\nkey_key.plasmovoice.settings:key.keyboard.h\r\nkey_key.magiccodex.open:key.keyboard.u\r\n')
    fs.mkdirSync(path.join(root,'config/magiccodex'), {recursive:true})
    const userUi = path.join(root,'config/magiccodex/ui-keys.properties')
    fs.writeFileSync(userUi, 'CURSOR=342\nCODEX=85\n')
    policy.apply(root, policy.capture(root))
    content = fs.readFileSync(target, 'utf8')
    assert(content.includes('key_key.plasmovoice.settings:key.keyboard.h'))
    assert(content.includes('key_key.magiccodex.open:key.keyboard.u'))
    assert(content.includes('key_key.inventory:key.keyboard.tab'))
    assert(content.includes('music:0.8'))
    assert.equal(fs.readFileSync(userUi,'utf8'), 'CURSOR=342\nCODEX=85\n')
    const before = fs.readFileSync(target)
    policy.apply(root, policy.capture(root))
    assert.deepEqual(fs.readFileSync(target), before)
    console.log('PASS new install shown defaults, old user keys/UI settings, unrelated options, missing-only fill and idempotence')
} finally { fs.rmSync(root, {recursive:true, force:true}) }
